package me.elephant1214.loadercatalog

import org.gradle.api.DefaultTask
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.MapProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.TaskAction

@CacheableTask
abstract class GenerateLoaderCatalog : DefaultTask() {
    @get:Input
    abstract val packageName: Property<String>

    @get:Input
    abstract val className: Property<String>

    /**
     * Bundle alias -> list of "group:name:version"
     */
    @get:Input
    abstract val bundles: MapProperty<String, List<String>>

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val pkg = packageName.get()
        val cls = className.get()
        val root = outputDir.get().asFile.apply { deleteRecursively() }
        val file = root.resolve("${pkg.replace('.', '/')}/$cls.java")
        file.parentFile.mkdirs()

        val fields = bundles.get().toSortedMap().entries.joinToString("\n\n") { (alias, coords) ->
            val fieldName = alias.replace(INVALID_IDENTIFIER_CHARS, "_").uppercase()
            val entries = coords.joinToString(",\n            ") { coord ->
                "new org.eclipse.aether.graph.Dependency(new org.eclipse.aether.artifact.DefaultArtifact(\"$coord\"), null)"
            }
            """
            |    public static final java.util.List<org.eclipse.aether.graph.Dependency> $fieldName = java.util.List.of(
            |           $entries
            |    );
            """.trimMargin()
        }

        file.writeText(
            """
            |// Generated by ${this::class.java.simpleName.removeSuffix("_Decorated")}. Do not edit.
            |package $pkg;
            |
            |public final class $cls {
            |    private $cls() {}
            |
            |$fields
            |}
            |""".trimMargin()
        )
    }

    private companion object {
        val INVALID_IDENTIFIER_CHARS = Regex("[^A-Za-z0-9_]")
    }
}
